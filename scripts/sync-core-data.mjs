#!/usr/bin/env node
/**
 * Orthotect Core Data Synchronizer
 * Compiles canonical schemas from core/fsm/*.json and core/tokens/*.json
 * into docs/core-models.js to eliminate client/server divergence and provide
 * a zero-CORS single source of truth for the Skill Studio and Live Benchmark.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const fsmDir = path.join(rootDir, 'core', 'fsm');
const tokensDir = path.join(rootDir, 'core', 'tokens');
const outputFile = path.join(rootDir, 'docs', 'core-models.js');

const fsmFiles = ['data-table-loader.json', 'modal-dialog.json', 'button-states.json'];
const fsmData = {};

for (const file of fsmFiles) {
  const filePath = path.join(fsmDir, file);
  if (!fs.existsSync(filePath)) {
    console.error(`❌ Missing required FSM file: ${filePath}`);
    process.exit(1);
  }
  fsmData[file] = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
}

const primPath = path.join(tokensDir, 'primitives.json');
const semPath = path.join(tokensDir, 'semantics.json');

if (!fs.existsSync(primPath) || !fs.existsSync(semPath)) {
  console.error(`❌ Missing required token files in ${tokensDir}`);
  process.exit(1);
}

const tokensData = {
  primitives: JSON.parse(fs.readFileSync(primPath, 'utf-8')),
  semantics: JSON.parse(fs.readFileSync(semPath, 'utf-8'))
};

const outputContent = `// Auto-generated by scripts/sync-core-data.mjs - DO NOT EDIT DIRECTLY.
// Single source of truth is in core/fsm/*.json and core/tokens/*.json
(function() {
  const coreData = ${JSON.stringify({ fsm: fsmData, tokens: tokensData }, null, 2)};
  if (typeof window !== 'undefined') {
    window.ORTHOTECT_CORE = coreData;
  }
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = coreData;
  }
})();
`;

fs.writeFileSync(outputFile, outputContent, 'utf-8');
console.log(`✅ [SYNC] Successfully synchronized core FSM models & DTCG tokens -> docs/core-models.js`);
